
import ast
import re


def review_code(code: str, language: str = "Python") -> str:
    """Provide free, local, rule-based code feedback."""

    if not code or not code.strip():
        return "Please enter some code to review."

    language = language.strip().lower()

    if language == "python":
        return _review_python(code)

    if language == "sql":
        return _review_sql(code)

    return (
        f"ℹ️ Local checks for {language} are not available yet.\n\n"
        "Currently supported: Python and SQL."
    )


def _review_python(code: str) -> str:
    """Check syntax and explain common errors and corrections."""

    try:
        tree = ast.parse(code)

    except SyntaxError as exc:
        line_number = exc.lineno or 1
        error_message = exc.msg

        corrected_code, explanation = _suggest_syntax_fix(code, exc)

        result = [
            "## ❌ Python Error Detected",
            "",
            f"**Error on line {line_number}:** {error_message}",
            "",
            "### 💡 Hint",
            _syntax_hint(error_message),
        ]

        if corrected_code:
            result.extend([
                "",
                "### ✅ Suggested corrected code",
                "```python",
                corrected_code,
                "```",
                "",
                "### 🧠 Why this correction works",
                explanation,
                "",
                "The suggested correction fixes the detected syntax issue. "
                "Check that it matches your intended logic.",
            ])

        result.extend([
            "",
            "ℹ️ These are local syntax checks and rule-based suggestions, "
            "not a full AI review.",
        ])

        return "\n".join(result)

    issues = []
    suggestions = []

    for number, line in enumerate(code.splitlines(), start=1):
        stripped = line.strip()

        if re.search(r"\bif\b.*(?<![=!<>])=(?!=)", stripped):
            issues.append(
                f"Line {number}: Possible use of `=` instead of `==` "
                "in an if condition."
            )
            suggestions.append(
                "Use `==` to compare values. A single `=` assigns a value."
            )

        if stripped.endswith("== True") or stripped.endswith("== False"):
            suggestions.append(
                f"Line {number}: Consider simplifying the boolean comparison."
            )

        if len(line) > 88:
            suggestions.append(
                f"Line {number}: Consider shortening this line for readability."
            )

    result = [
        "## ✅ Python Syntax Check Passed",
        "",
        "Your code has valid Python syntax!",
        "",
        "### 📝 Code explanation",
        _explain_python(tree),
        "",
        "### ▶️ Output",
        "This reviewer does not execute submitted code. "
        "Run the code in a suitable Python environment to verify its output.",
    ]

    if issues:
        result.extend([
            "",
            "### ⚠️ Potential issues",
            *[f"- {item}" for item in dict.fromkeys(issues)],
        ])

    if suggestions:
        result.extend([
            "",
            "### 💡 Suggestions",
            *[f"- {item}" for item in dict.fromkeys(suggestions)],
        ])
    else:
        result.extend([
            "",
            "### 🌟 Review feedback",
            "No obvious issues were found by the basic local checks.",
        ])

    result.extend([
        "",
        "ℹ️ Valid syntax does not guarantee logical correctness. "
        "Explanations are rule-based, not generated by a language model.",
    ])

    return "\n".join(result)


def _syntax_hint(message: str) -> str:
    """Return a useful hint for common Python syntax errors."""

    if "expected ':'" in message:
        return (
            "Function definitions, if statements, loops, and class "
            "definitions usually need a colon (`:`) at the end."
        )

    if "was never closed" in message or "unexpected EOF" in message:
        return (
            "Check that every opening bracket, parenthesis, and quote is closed."
        )

    if "expected an indented block" in message:
        return (
            "Indent the code inside the function, loop, or conditional."
        )

    if "invalid syntax" in message:
        return (
            "Check operators, spelling, brackets, commas, and the line "
            "mentioned in the error."
        )

    return "Review the reported line and check Python syntax and indentation."


def _suggest_syntax_fix(
    code: str,
    exc: SyntaxError,
) -> tuple[str | None, str]:
    """Apply only a simple syntax correction when it validates."""

    lines = code.splitlines()
    line_number = exc.lineno

    if not line_number or not (1 <= line_number <= len(lines)):
        return None, ""

    line = lines[line_number - 1]

    if "expected ':'" in exc.msg and not line.rstrip().endswith(":"):
        lines[line_number - 1] = line.rstrip() + ":"
        candidate = "\n".join(lines)

        try:
            ast.parse(candidate)

            explanation = (
                "A colon (`:`) was added at the end of the statement. "
                "Python uses this colon to mark the start of an indented "
                "block, such as a function body, an if body, or a loop body."
            )

            return candidate, explanation

        except SyntaxError:
            return None, ""

    return None, ""


def _explain_python(tree: ast.AST) -> str:
    """Explain common Python statements using simple rules."""

    explanations = []

    for node in getattr(tree, "body", []):

        if isinstance(node, ast.FunctionDef):
            arguments = [arg.arg for arg in node.args.args]

            if arguments:
                explanations.append(
                    f"- Defines a function named `{node.name}` that accepts "
                    + ", ".join(f"`{arg}`" for arg in arguments)
                    + "."
                )
            else:
                explanations.append(
                    f"- Defines a function named `{node.name}`."
                )

            if any(
                isinstance(child, ast.Return)
                for child in ast.walk(node)
            ):
                explanations.append(
                    f"- `return` sends a value from `{node.name}` "
                    "back to the code that called it."
                )

        elif isinstance(node, ast.Assign):
            names = [
                target.id
                for target in node.targets
                if isinstance(target, ast.Name)
            ]

            if names:
                explanations.append(
                    f"- Assigns a value to `{', '.join(names)}`."
                )

            if isinstance(node.value, ast.BinOp):
                operator = node.value.op

                if isinstance(operator, ast.Add):
                    explanations.append(
                        "- The `+` operator adds values together."
                    )

                elif isinstance(operator, ast.Sub):
                    explanations.append(
                        "- The `-` operator subtracts one value from another."
                    )

                elif isinstance(operator, ast.Mult):
                    explanations.append(
                        "- The `*` operator multiplies values."
                    )

        elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
            call = node.value

            if (
                isinstance(call.func, ast.Name)
                and call.func.id == "print"
            ):
                explanations.append(
                    "- `print()` displays information on the screen."
                )

        elif isinstance(node, ast.If):
            explanations.append(
                "- The `if` statement runs code when a condition is true."
            )

        elif isinstance(node, (ast.For, ast.While)):
            explanations.append(
                "- This loop repeats instructions."
            )

    if not explanations:
        return (
            "The code has valid syntax. Review its statements and "
            "expressions to understand their purpose."
        )

    return "\n".join(dict.fromkeys(explanations))


def _review_sql(code: str) -> str:
    """Provide basic SQL checks without executing queries."""

    normalized = " ".join(code.strip().lower().split())
    issues = []
    suggestions = []

    if not re.match(
        r"^(select|insert|update|delete|create|alter|drop)\b",
        normalized,
    ):
        issues.append(
            "The query does not start with a recognized common SQL statement."
        )

    if normalized.startswith("select"):

        if " from " not in f" {normalized} ":
            issues.append(
                "A SELECT query usually needs a FROM clause."
            )

        if re.search(r"\bselect\s+\*", normalized):
            suggestions.append(
                "SELECT * retrieves every column. Consider listing "
                "only the columns you need."
            )

        if re.search(r"\bwhere\s*$", normalized):
            issues.append(
                "The WHERE clause is incomplete."
            )

    if normalized.count("(") != normalized.count(")"):
        issues.append(
            "The query may contain unmatched parentheses."
        )

    if issues or suggestions:
        result = ["## 📝 SQL Review"]

        if issues:
            result.extend([
                "",
                "### ⚠️ Potential issues",
                *[f"- {item}" for item in issues],
            ])

        if suggestions:
            result.extend([
                "",
                "### 💡 Suggestions",
                *[f"- {item}" for item in suggestions],
            ])

        result.extend([
            "",
            "These are basic pattern checks. The query has not "
            "been executed against a database.",
        ])

        return "\n".join(result)

    return (
        "## ✅ Basic SQL Check Passed\n\n"
        "No obvious issues were found by the basic checks.\n\n"
        "💡 Verify the table names, column names, and query results "
        "against your database.\n\n"
        "ℹ️ This is not a full SQL parser, and the query has not "
        "been executed against a database."
    )
